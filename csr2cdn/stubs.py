"""Generating a typed module so IDEs can complete asset names.

Attribute completion works at runtime for free, because
:class:`~csr2cdn.database.AssetCollection` implements ``__dir__``. IPython,
Jupyter and a plain REPL will all offer asset names. Static analysers (PyCharm,
Pylance, mypy) never run your code, so they need a declaration file.

:func:`generate` writes a pair of files next to each other::

    csr2_assets.py    # loads the database at import time
    csr2_assets.pyi   # declares every asset name as an Asset

Then in your own code::

    from csr2_assets import assets, database

    assets.Lamborghini_AventadorLP7004_2011_loda.version

The ``.pyi`` shadows the ``.py`` for type checkers, which is exactly what makes
completion work, while at runtime the ``.py`` loads the real database.
"""

from __future__ import annotations

import os
from typing import Optional, Union

from csr2cdn.database import AssetDatabase

PathLike = Union[str, "os.PathLike[str]"]

_MODULE_TEMPLATE = '''"""Generated by csr2cdn {version}. Do not edit.

Regenerate with:
    csr2cdn stubs {source_hint} --output {module_name}
"""

import os

from csr2cdn import AssetDatabase

DATABASE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), {database_file!r})

database = AssetDatabase.load(DATABASE_PATH)
assets = database.assets

__all__ = ["DATABASE_PATH", "database", "assets"]
'''

_STUB_HEADER = '''"""Generated by csr2cdn {version}. Do not edit.

branch_name: {branch_name}
version: {database_version}
assets: {asset_count}
"""

from csr2cdn import Asset, AssetCollection, AssetDatabase

DATABASE_PATH: str
database: AssetDatabase

class _Assets(AssetCollection):
'''


def generate(
    database: AssetDatabase,
    output: PathLike,
    database_file: Optional[str] = None,
    source_hint: str = "asset_database.json",
) -> "tuple[str, str]":
    """Write ``<output>.py`` and ``<output>.pyi`` for *database*.

    :param output: path of the module to write, with or without ``.py``.
    :param database_file: the JSON file the generated module loads at runtime.
        Defaults to ``<output>.json``, which is written as well.
    :returns: the paths of the module and the stub.
    """
    output = os.fspath(output)
    if output.endswith(".py") or output.endswith(".pyi"):
        output = output.rsplit(".py", 1)[0]
    module_path = output + ".py"
    stub_path = output + ".pyi"
    module_name = os.path.basename(output)
    directory = os.path.dirname(os.path.abspath(module_path))
    os.makedirs(directory, exist_ok=True)

    if database_file is None:
        database_file = module_name + ".json"
        database.save(os.path.join(directory, database_file))

    from csr2cdn import __version__

    with open(module_path, "w", encoding="utf-8") as handle:
        handle.write(
            _MODULE_TEMPLATE.format(
                version=__version__,
                module_name=module_name,
                database_file=database_file,
                source_hint=source_hint,
            )
        )

    seen = set()
    lines = []
    for asset in database.assets:
        alias = asset.alias
        if alias in seen:
            continue
        seen.add(alias)
        lines.append(f"    {alias}: Asset\n")

    with open(stub_path, "w", encoding="utf-8") as handle:
        handle.write(
            _STUB_HEADER.format(
                version=__version__,
                branch_name=database.branch_name,
                database_version=database.version,
                asset_count=len(database.assets),
            )
        )
        if lines:
            handle.writelines(lines)
        else:
            handle.write("    ...\n")
        handle.write("\nassets: _Assets\n")

    return module_path, stub_path
